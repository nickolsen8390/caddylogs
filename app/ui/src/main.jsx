import React from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import App from './App.jsx';
import './styles.css';

// The service worker (public/sw.js) that makes this installable. Browsers
// allow one only over HTTPS (or localhost); elsewhere this is skipped, and
// the app works as it always has. A browser refusing it — storage blocked,
// a frame on another site — costs nothing but the offline page.
if ('serviceWorker' in navigator && import.meta.env.PROD) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch(() => {});
  });
}

createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <BrowserRouter>
      <App />
    </BrowserRouter>
  </React.StrictMode>
);
